  // 2^k factorial effects (contrast method)
  // ---------------------------------------------------------------------
  S.factorial = function (cols, params) {
    const names = params.factors, k = params.k, y = cols.y, N = y.length;
    const terms = [];
    for (let mask = 1; mask < (1 << k); mask++) { const t = []; for (let j = 0; j < k; j++) if (mask & (1 << j)) t.push(names[j]); terms.push(t); }
    const gm = mean(y);
    const out = { k: k, N: N, replicates: params.replicates, grand_mean: gm, effects: {}, coefficients: {}, intercept: gm };
    const contrasts = {};
    for (const t of terms) {
      const label = t.join("");
      let c = 0;
      for (let i = 0; i < N; i++) { let s = 1; for (const nm of t) s *= cols[nm][i]; c += s * y[i]; }
      contrasts[label] = c;
      out.effects[label] = c / (N / 2);
      out.coefficients[label] = c / N;
    }
    if (N > (1 << k)) {
      let sst = 0; for (const v of y) sst += (v - gm) * (v - gm);
      const an = {}; let ssModel = 0;
      for (const label in contrasts) { const ss = contrasts[label] * contrasts[label] / N; an[label] = { ss: ss, df: 1, ms: ss }; ssModel += ss; }
      const dfRes = N - (1 << k), ssRes = sst - ssModel, mse = ssRes / dfRes;
      for (const label in contrasts) { an[label].F = an[label].ss / mse; an[label].p = S.fSf(an[label].F, 1, dfRes); }
      an.residual = { ss: ssRes, df: dfRes, ms: mse };
      an.total = { ss: sst, df: N - 1 };
      out.anova = an;
      out.residual_sd = Math.sqrt(mse);
      out.se_effect = 2 * Math.sqrt(mse / N);
      out.r2 = 1 - ssRes / sst;
      out.r2_adj = 1 - (ssRes / dfRes) / (sst / (N - 1));
    }
    out.cell_means = {};
    const cells = {};
    for (let i = 0; i < N; i++) {
      let key = ""; for (const nm of names) if (cols[nm][i] > 0) key += nm.toLowerCase();
      if (!key) key = "(1)";
      (cells[key] = cells[key] || []).push(y[i]);
    }
    for (const key in cells) out.cell_means[key] = mean(cells[key]);
    return out;
  };

