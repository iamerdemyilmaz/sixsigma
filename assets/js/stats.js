  function leveneF(samples) {
    const devs = samples.map(function (s) { const md = median(s); return s.map(function (v) { return Math.abs(v - md); }); });
    return oneWay(devs);
  }
  function oneWay(samples) {
    const k = samples.length; let N = 0; for (const s of samples) N += s.length;
    const all = []; for (const s of samples) for (const v of s) all.push(v);
    const gm = mean(all);
    let ssb = 0, ssw = 0;
    for (const s of samples) { const m = mean(s); ssb += s.length * (m - gm) * (m - gm); for (const v of s) ssw += (v - m) * (v - m); }
    const F = (ssb / (k - 1)) / (ssw / (N - k));
    return { F: F, p: S.fSf(F, k - 1, N - k), ssb: ssb, ssw: ssw, N: N, k: k, gm: gm };
  }

  S.ttest2 = function (cols, params) {
    const alpha = params.alpha === undefined ? 0.05 : params.alpha;
    const groups = []; for (const g of cols.group) if (groups.indexOf(g) < 0) groups.push(g);
    const a = cols.x.filter(function (_, i) { return cols.group[i] === groups[0]; });
    const b = cols.x.filter(function (_, i) { return cols.group[i] === groups[1]; });
    const na = a.length, nb = b.length, ma = mean(a), mb = mean(b), va = sd(a) * sd(a), vb = sd(b) * sd(b);
    const diff = ma - mb;
    const sp = Math.sqrt(((na - 1) * va + (nb - 1) * vb) / (na + nb - 2));
    const seP = sp * Math.sqrt(1 / na + 1 / nb), dfp = na + nb - 2, tp = diff / seP, tc = S.tPpf(1 - alpha / 2, dfp);
    const seW = Math.sqrt(va / na + vb / nb);
    const dfw = Math.pow(va / na + vb / nb, 2) / (Math.pow(va / na, 2) / (na - 1) + Math.pow(vb / nb, 2) / (nb - 1));
    const tw = diff / seW, tcw = S.tPpf(1 - alpha / 2, dfw);
    const Fv = va / vb;
    const lev = leveneF([a, b]);
    return { groups: groups, n: [na, nb], means: [ma, mb], sds: [Math.sqrt(va), Math.sqrt(vb)], diff: diff,
      pooled: { sp: sp, se: seP, t: tp, df: dfp, p: 2 * S.tSf(Math.abs(tp), dfp), ci: [diff - tc * seP, diff + tc * seP] },
      welch: { se: seW, t: tw, df: dfw, p: 2 * S.tSf(Math.abs(tw), dfw), ci: [diff - tcw * seW, diff + tcw * seW] },
      cohen_d: diff / sp,
      variance_tests: { F: Fv, F_p: 2 * Math.min(S.fCdf(Fv, na - 1, nb - 1), S.fSf(Fv, na - 1, nb - 1)), levene_W: lev.F, levene_p: lev.p },
      alpha: alpha };
  };

  S.anova1 = function (cols, params) {
    const groups = []; for (const g of cols.group) if (groups.indexOf(g) < 0) groups.push(g);
    const samples = groups.map(function (g) { return cols.x.filter(function (_, i) { return cols.group[i] === g; }); });
    const r = oneWay(samples), lev = leveneF(samples);
    return { groups: groups, n: samples.map(function (s) { return s.length; }), means: samples.map(mean), sds: samples.map(sd), grand_mean: r.gm,
      ss_between: r.ssb, ss_within: r.ssw, ss_total: r.ssb + r.ssw, df_between: r.k - 1, df_within: r.N - r.k,
      ms_between: r.ssb / (r.k - 1), ms_within: r.ssw / (r.N - r.k), F: r.F, p: r.p, eta2: r.ssb / (r.ssb + r.ssw),
      pooled_sd: Math.sqrt(r.ssw / (r.N - r.k)), levene_W: lev.F, levene_p: lev.p };
  };

  S.oneSample = function (x, mu0, alpha) {
    if (alpha === undefined) alpha = 0.05;
    const n = x.length, m = mean(x), s = sd(x), se = s / Math.sqrt(n), t = (m - mu0) / se, tc = S.tPpf(1 - alpha / 2, n - 1);
    return { n: n, mean: m, s: s, se: se, mu0: mu0, t: t, df: n - 1, p: 2 * S.tSf(Math.abs(t), n - 1), ci: [m - tc * se, m + tc * se], cohen_d: (m - mu0) / s };
  };
  S.paired = function (cols, params) {
    const d = cols.after.map(function (v, i) { return v - cols.before[i]; });
    const out = S.oneSample(d, 0, params.alpha);
    out.mean_before = mean(cols.before); out.mean_after = mean(cols.after); out.differences = d;
    return out;
  };

  S.regression = function (cols, params) {
    const x = cols.x, y = cols.y, n = x.length, alpha = (params && params.alpha !== undefined) ? params.alpha : 0.05;
    const mx = mean(x), my = mean(y);
    let sxx = 0, sxy = 0, syy = 0;
    for (let i = 0; i < n; i++) { sxx += (x[i] - mx) * (x[i] - mx); sxy += (x[i] - mx) * (y[i] - my); syy += (y[i] - my) * (y[i] - my); }
    const b1 = sxy / sxx, b0 = my - b1 * mx;
    const fitted = x.map(function (v) { return b0 + b1 * v; }), resid = y.map(function (v, i) { return v - fitted[i]; });
    let ssr = 0; for (const r of resid) ssr += r * r;
    const sse = syy - ssr, s = Math.sqrt(ssr / (n - 2)), seB1 = s / Math.sqrt(sxx), seB0 = s * Math.sqrt(1 / n + mx * mx / sxx);
    const t1 = b1 / seB1, tc = S.tPpf(1 - alpha / 2, n - 2), F = sse / (ssr / (n - 2));
    return { n: n, slope: b1, intercept: b0, se_slope: seB1, se_intercept: seB0, t_slope: t1, p_slope: 2 * S.tSf(Math.abs(t1), n - 2),
      slope_ci: [b1 - tc * seB1, b1 + tc * seB1], r: sxy / Math.sqrt(sxx * syy), r2: 1 - ssr / syy, r2_adj: 1 - (ssr / (n - 2)) / (syy / (n - 1)),
      s: s, F: F, p_F: S.fSf(F, 1, n - 2), ss_regression: sse, ss_residual: ssr, ss_total: syy, fitted: fitted, residuals: resid, mean_x: mx, mean_y: my };
  };

  S.sampleSize = function (params) {
    const alpha = params.alpha, beta = params.beta, sides = params.sides || 2;
    const two = params.design === "two-sample", mult = two ? 2 : 1;
    const ratio = Math.pow(params.sigma / params.delta, 2);
    const za = S.normPpf(1 - alpha / sides), zb = S.normPpf(1 - beta);
    const nz = mult * (za + zb) * (za + zb) * ratio;
    const n = Math.ceil(nz);
    let nt = n; const seen = {};
    for (let it = 0; it < 50; it++) {
      const df = two ? 2 * nt - 2 : nt - 1;
      const nn = Math.ceil(mult * Math.pow(S.tPpf(1 - alpha / sides, df) + S.tPpf(1 - beta, df), 2) * ratio);
      if (nn === nt || seen[nn]) { nt = Math.max(nn, nt); break; }
      seen[nt] = true; nt = nn;
    }
    return { alpha: alpha, beta: beta, power: 1 - beta, delta: params.delta, sigma: params.sigma, sides: sides,
      design: params.design || "one-sample", z_alpha: za, z_beta: zb, n_z_exact: nz, n_z: n, n_t: nt };
  };

  // ---------------------------------------------------------------------
  // Sigma level, DPMO, DPU, RTY
  // ---------------------------------------------------------------------
  S.dpmo = function (defects, units, opportunities) {
    const dpo = defects / (units * opportunities), dpmo = dpo * 1e6, dpu = defects / units;
    const zlt = S.normPpf(1 - dpmo / 1e6);
    return { defects: defects, units: units, opportunities: opportunities, dpmo: dpmo, dpu: dpu, dpo: dpo,
      yield_fty: Math.exp(-dpu), yield_from_dpmo: 1 - dpmo / 1e6, sigma_long_term: zlt, sigma_level_shifted: zlt + 1.5 };
  };
  // Sigma level k to PPM: centred two-sided 2·P(Z>k); with the 1.5σ shift the
  // one-sided tail P(Z>k−shift) (the convention behind "3.4 PPM at six sigma")
  // and the two-sided version adding the far tail P(Z>k+shift).
  S.sigmaTable = function (params) {
    const shift = params.shift === undefined ? 1.5 : params.shift, levels = params.levels.map(Number);
    const out = { shift: shift, levels: levels, ppm_centered_two_sided: [], ppm_shifted_one_sided: [], ppm_shifted_two_sided: [], yield_shifted_one_sided: [] };
    for (const k of levels) {
      const near = S.normSf(k - shift), far = S.normSf(k + shift);
      out.ppm_centered_two_sided.push(2e6 * S.normSf(k));
      out.ppm_shifted_one_sided.push(1e6 * near);
      out.ppm_shifted_two_sided.push(1e6 * (near + far));
      out.yield_shifted_one_sided.push(1 - near);
    }
    if (params.ppm_targets) {
      out.ppm_targets = params.ppm_targets.map(Number);
      out.z_of_targets = out.ppm_targets.map(function (p) { return S.normPpf(1 - p / 1e6); });
      out.sigma_level_of_targets = out.z_of_targets.map(function (z) { return z + shift; });
    }
    return out;
  };
  S.sigmaFromDpmo = function (dpmo, shift) { return S.normPpf(1 - dpmo / 1e6) + (shift === undefined ? 1.5 : shift); };
  S.dpmoFromSigma = function (sigma, shift) { return S.normSf(sigma - (shift === undefined ? 1.5 : shift)) * 1e6; };
  S.rty = function (yields) { let r = 1; for (const y of yields) r *= y; return r; };

  return S;
