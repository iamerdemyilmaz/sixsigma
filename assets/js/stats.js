  function ppmBlock(m, sig, usl, lsl) {
    const pu = (usl !== null && usl !== undefined) ? S.normSf((usl - m) / sig) : 0;
    const pl = (lsl !== null && lsl !== undefined) ? S.normCdf((lsl - m) / sig) : 0;
    return { ppm_upper: pu * 1e6, ppm_lower: pl * 1e6, ppm_total: (pu + pl) * 1e6 };
  }
  function indices(m, sig, usl, lsl, target, nl, nu) {
    const has = function (v) { return v !== null && v !== undefined; };
    const out = {};
    const cu = has(usl) ? (usl - m) / (3 * sig) : null, cl = has(lsl) ? (m - lsl) / (3 * sig) : null;
    out.u = cu; out.l = cl;
    const both = [cu, cl].filter(has);
    out.k_index = both.length ? Math.min.apply(null, both) : null;
    if (has(usl) && has(lsl)) {
      out.p = (usl - lsl) / (6 * sig);
      out.k = Math.abs((usl + lsl) / 2 - m) / ((usl - lsl) / 2);
      if (has(target)) out.pm = (usl - lsl) / (6 * Math.sqrt(sig * sig + (m - target) * (m - target)));
    } else {
      out.p = null;
      const lo = has(lsl) ? lsl : nl, hi = has(usl) ? usl : nu;
      if (has(lo) && has(hi)) out.p_natural = (hi - lo) / (6 * sig);
    }
    Object.assign(out, ppmBlock(m, sig, usl, lsl));
    return out;
  }

