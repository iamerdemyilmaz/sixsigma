  S.grrFromMs = function (msf, dff, msr, dfr, P, O, R, tolerance, ksv, alpha) {
    const Fi = msf.interaction / msf.repeatability;
    const pi = S.fSf(Fi, dff.interaction, dff.repeatability);
    const reduced = pi > alpha;
    const out = { interaction_F: Fi, interaction_p: pi, interaction_removed: reduced, alpha_remove: alpha };
    let rep, op, inter, part;
    if (reduced) {
      rep = msr.repeatability; inter = 0;
      op = Math.max(0, (msr.operator - rep) / (P * R)); part = Math.max(0, (msr.part - rep) / (O * R));
      out.anova_used = "reduced (interaction pooled into repeatability)";
      out.F_operator = msr.operator / rep; out.F_part = msr.part / rep;
      out.p_operator = S.fSf(out.F_operator, dfr.operator, dfr.repeatability);
      out.p_part = S.fSf(out.F_part, dfr.part, dfr.repeatability);
    } else {
      rep = msf.repeatability; inter = Math.max(0, (msf.interaction - rep) / R);
      op = Math.max(0, (msf.operator - msf.interaction) / (P * R)); part = Math.max(0, (msf.part - msf.interaction) / (O * R));
      out.anova_used = "full (with part x operator interaction)";
      out.F_operator = msf.operator / msf.interaction; out.F_part = msf.part / msf.interaction;
      out.p_operator = S.fSf(out.F_operator, dff.operator, dff.interaction);
      out.p_part = S.fSf(out.F_part, dff.part, dff.interaction);
    }
    const vc = { repeatability: rep, reproducibility: op + inter, operator: op, interaction: inter, grr: rep + op + inter, part: part, total: rep + op + inter + part };
    out.varcomp = vc;
    out.pct_contribution = {}; out.sd = {}; out.study_var = {}; out.pct_study_var = {};
    if (tolerance) { out.tolerance = tolerance; out.pct_tolerance = {}; }
    out.study_var_k = ksv;
    for (const k in vc) {
      out.pct_contribution[k] = 100 * vc[k] / vc.total;
      out.sd[k] = Math.sqrt(vc[k]);
      out.study_var[k] = ksv * out.sd[k];
      out.pct_study_var[k] = 100 * out.sd[k] / Math.sqrt(vc.total);
      if (tolerance) out.pct_tolerance[k] = 100 * ksv * out.sd[k] / tolerance;
    }
    out.ndc_exact = out.sd.grr > 0 ? 1.41 * out.sd.part / out.sd.grr : null;
    out.ndc = out.ndc_exact === null ? null : Math.max(1, Math.floor(out.ndc_exact));
    return out;
  };

  S.grr = function (cols, params) {
    const parts = cols.part.map(function (v) { return typeof v === "number" ? String(Math.round(v)) : String(v); });
    const ops = cols.operator.map(String), y = cols.y, N = y.length;
    const uniq = function (a) { const o = []; for (const v of a) if (o.indexOf(v) < 0) o.push(v); return o; };
    const up = uniq(parts), uo = uniq(ops), P = up.length, O = uo.length, R = Math.round(N / (P * O));
    const gm = mean(y);
    const pm = {}, om = {}, cm = {};
    up.forEach(function (p) { pm[p] = mean(y.filter(function (_, i) { return parts[i] === p; })); });
    uo.forEach(function (o) { om[o] = mean(y.filter(function (_, i) { return ops[i] === o; })); });
    up.forEach(function (p) { uo.forEach(function (o) { cm[p + "|" + o] = mean(y.filter(function (_, i) { return parts[i] === p && ops[i] === o; })); }); });
    const sq = function (obj) { let s = 0; for (const k in obj) s += (obj[k] - gm) * (obj[k] - gm); return s; };
    const ssPart = O * R * sq(pm), ssOp = P * R * sq(om), ssCells = R * sq(cm);
    const ssInt = ssCells - ssPart - ssOp;
    let ssTot = 0; for (const v of y) ssTot += (v - gm) * (v - gm);
    const ssRep = ssTot - ssCells;
    const dff = { part: P - 1, operator: O - 1, interaction: (P - 1) * (O - 1), repeatability: P * O * (R - 1) };
    const msf = { part: ssPart / dff.part, operator: ssOp / dff.operator, interaction: ssInt / dff.interaction, repeatability: ssRep / dff.repeatability };
    const dfr = { part: P - 1, operator: O - 1, repeatability: dff.interaction + dff.repeatability };
    const msr = { part: msf.part, operator: msf.operator, repeatability: (ssInt + ssRep) / dfr.repeatability };
    const out = { parts: P, operators: O, replicates: R, N: N,
      ss_full: { part: ssPart, operator: ssOp, interaction: ssInt, repeatability: ssRep, total: ssTot },
      ms_full: msf, df_full: dff, ms_reduced: msr, df_reduced: dfr, grand_mean: gm };
    Object.assign(out, S.grrFromMs(msf, dff, msr, dfr, P, O, R, params.tolerance, params.study_var_k || 6, params.alpha_remove === undefined ? 0.05 : params.alpha_remove));
    out.operator_means = om; out.part_means = pm;
    return out;
  };

